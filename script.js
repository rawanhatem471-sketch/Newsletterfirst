/* =========================================================
   GET NEWSLETTER ID
========================================================= */

function getNewsletterId() {

    const params = new URLSearchParams(
        window.location.search
    );

    return params.get("id");

}



/* =========================================================
   SHARE
========================================================= */

function shareNews(title) {

    if (navigator.share) {

        navigator.share({

            title: "ELPAI",

            text: title

        });

    }

    else {

        navigator.clipboard
            .writeText(title)
            .then(() => {

                alert("تم نسخ عنوان الخبر");

            });

    }

}



/* =========================================================
   CREATE NEWS CARD
========================================================= */

function createCard(news, featured = false) {

    return `

        <article
            class="${featured ? "featured-news" : "news-card"}">

            <div class="news-meta">

                <span class="news-dot"></span>

                ${featured
                    ? "خبر رئيسي"
                    : "مستجد قانوني"}

            </div>


            <h4>
                ${news.title}
            </h4>


            <p>
                ${news.text}
            </p>


            <div class="news-actions">

                <button
                    class="share-button"
                    onclick='shareNews(${JSON.stringify(news.title)})'>

                    مشاركة الآن ↗

                </button>

            </div>

        </article>

    `;

}



/* =========================================================
   CREATE SECTION
========================================================= */

function createSection(section) {

    let html = `

        <section class="news-section">

            <div class="section-heading">

                <span class="section-line"></span>

                <h3>
                    ${section.title}
                </h3>

            </div>

    `;


    /* EMPTY */

    if (section.empty) {

        html += `

            <div class="empty-state">

                <div class="empty-icon">
                    ○
                </div>

                <strong>
                    لا توجد نتائج في هذا القسم حالياً
                </strong>

                <span>
                    سيتم عرض المحتوى هنا عند توفره.
                </span>

            </div>

        `;

        html += `</section>`;

        return html;

    }


    /* FEATURED */

    if (section.featured) {

        html += createCard(
            section.featured,
            true
        );


        if (section.cards) {

            html += `

                <div class="news-grid">

                    ${section.cards
                        .map(card => createCard(card))
                        .join("")}

                </div>

            `;

        }

    }


    /* COUNTRIES */

    if (section.countries) {

        section.countries.forEach(country => {

            html += `

                <div class="country-heading">

                    <span class="country-icon">

                        ${country.code}

                    </span>

                    <h4>
                        ${country.name}
                    </h4>

                </div>


                <div class="news-grid">

                    ${country.cards
                        .map(card => createCard(card))
                        .join("")}

                </div>

            `;

        });

    }


    /* NORMAL CARDS */

    if (
        !section.featured &&
        !section.countries &&
        section.cards
    ) {

        html += `

            <div class="news-grid">

                ${section.cards
                    .map(card => createCard(card))
                    .join("")}

            </div>

        `;

    }


    html += `</section>`;

    return html;

}



